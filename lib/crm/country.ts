const HAS_CJK = /[\u4e00-\u9fa5]/;

/** 中文国名转英文；已经是英文（或空值）就原样返回。 */
export const toEnglishCountry = (value?: string | null): string => {
  const text = (value ?? "").trim();
  if (!text) return "";
  if (!HAS_CJK.test(text)) return text;
  return ZH_TO_EN[text] ?? text;
};
